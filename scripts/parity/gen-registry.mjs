#!/usr/bin/env node
// Generates crates/lq-check/src/registry.rs and checks/mod.rs from upstream's
// allChecks (meta only), plus a stub checks/<name>.rs for each check that has no
// file yet. Rerun only when upstream's check list changes. Existing check files
// are never touched.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, oracleRequire } from './lib.mjs';

const { allChecks } = oracleRequire('@shopify/theme-check-common');
const index = fs.readFileSync(
  path.join(ROOT, 'reference/theme-tools/packages/theme-check-common/src/checks/index.ts'),
  'utf8',
);
const names = index
  .slice(index.indexOf('export const allChecks'))
  .match(/= \[([\s\S]*?)\];/)[1]
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);
if (names.length !== allChecks.length) throw new Error('allChecks mismatch');

const snake = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();
const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, '\\u{$1}');
const SEV = ['Severity::Error', 'Severity::Warning', 'Severity::Info'];
const TARGET = {
  all: 'ConfigTarget::All',
  recommended: 'ConfigTarget::Recommended',
  'theme-app-extension': 'ConfigTarget::ThemeAppExtension',
};

function defaultValue(v) {
  if (v === undefined) return 'None';
  if (typeof v === 'boolean') return `Some(DefaultValue::Bool(${v}))`;
  if (typeof v === 'number') return `Some(DefaultValue::Num(${Number.isInteger(v) ? v + '.0' : v}))`;
  if (typeof v === 'string') return `Some(DefaultValue::Str(${lit(v)}))`;
  if (Array.isArray(v))
    return v.length
      ? `Some(DefaultValue::StrArray(&[${v.map(lit).join(', ')}]))`
      : 'Some(DefaultValue::EmptyArray)';
  if (v === null) return 'Some(DefaultValue::Null)';
  throw new Error(`unsupported default ${JSON.stringify(v)}`);
}

function prop(p) {
  const { type, defaultValue: d, optional, properties, itemType } = p.options;
  const ty = { string: 'String', number: 'Number', boolean: 'Boolean', object: 'Object', array: 'Array' }[type];
  const props = properties ? schema(properties) : '&[]';
  const item = itemType ? `Some(&${prop(itemType)})` : 'None';
  return `SchemaProp { ty: SchemaType::${ty}, default: ${defaultValue(d)}, optional: ${!!optional}, properties: ${props}, item_type: ${item} }`;
}

function schema(s) {
  const entries = Object.entries(s ?? {});
  if (!entries.length) return '&[]';
  return `&[${entries.map(([k, v]) => `(${lit(k)}, ${prop(v)})`).join(', ')}]`;
}

const mods = names.map(snake);
let reg = `//! All checks of upstream's \`allChecks\`, in order. Generated by
//! \`scripts/parity/gen-registry.mjs\`. A check is implemented when its
//! \`checks/<name>.rs\` exports something other than \`CheckImpl::NotImplemented\`.

use crate::api::*;
use crate::checks;
use lq_theme::config::{CheckInfo, DefaultValue, SchemaProp, SchemaType};

pub static REGISTRY: &[CheckDef] = &[\n`;
allChecks.forEach((c, i) => {
  const m = c.meta;
  reg += `    CheckDef {
        meta: CheckMeta {
            code: ${lit(m.code)},
            name: ${lit(m.name)},
            description: ${lit(m.docs.description)},
            recommended: ${!!m.docs.recommended},
            url: ${m.docs.url ? `Some(${lit(m.docs.url)})` : 'None'},
            severity: ${SEV[m.severity]},
            kind: SourceCodeType::${m.type === 'JSON' ? 'Json' : 'LiquidHtml'},
            aliases: &[${(m.aliases ?? []).map(lit).join(', ')}],
            targets: &[${(m.targets ?? []).map((t) => TARGET[t]).join(', ')}],
            schema: ${schema(m.schema)},
            deprecated: ${!!m.deprecated},
        },
        imp: checks::${mods[i]}::IMPL,
    },\n`;
});
reg += `];

/// The registry as \`lq_theme::config\` wants it.
pub static CONFIG_REGISTRY: &[CheckInfo] = &[\n`;
allChecks.forEach((c) => {
  const m = c.meta;
  reg += `    CheckInfo { code: ${lit(m.code)}, aliases: &[${(m.aliases ?? []).map(lit).join(', ')}], schema: ${schema(m.schema)} },\n`;
});
reg += `];

/// The definition(s) for a code. Two definitions share \`MaxFileSize\`.
pub fn find(code: &str) -> impl Iterator<Item = &'static CheckDef> + '_ {
    REGISTRY.iter().filter(move |d| d.meta.code == code)
}
`;
fs.writeFileSync(path.join(ROOT, 'crates/lq-check/src/registry.rs'), reg);

const checksDir = path.join(ROOT, 'crates/lq-check/src/checks');
fs.mkdirSync(checksDir, { recursive: true });
let mod = `//! One file per check; \`scripts/parity/gen-registry.mjs\` lists them.\n//! A helper shared by several checks goes in \`shared\`.\n\npub mod shared;\n`;
names.forEach((name, i) => {
  mod += `pub mod ${mods[i]};\n`;
  const file = path.join(checksDir, `${mods[i]}.rs`);
  if (!fs.existsSync(file)) {
    fs.writeFileSync(
      file,
      `//! \`${name}\`: not ported yet. See \`crates/lq-check/PORTING.md\`.\n\nuse crate::api::CheckImpl;\n\npub const IMPL: CheckImpl = CheckImpl::NotImplemented;\n`,
    );
  }
});
fs.writeFileSync(path.join(checksDir, 'mod.rs'), mod);
if (!fs.existsSync(path.join(checksDir, 'shared.rs'))) {
  fs.writeFileSync(path.join(checksDir, 'shared.rs'), '//! Helpers shared by several checks.\n');
}
console.log(`[gen-registry] ${names.length} checks`);
