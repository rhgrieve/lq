#!/usr/bin/env node
// `--auto-correct` writes to disk, so it's compared as the files it leaves behind.
//   1. A theme whose fixes all apply: upstream's checkAndAutofix, `lq --upstream-bugs` and default `lq` agree.
//   2. AutofixAbort: a locale with a comment header stops upstream; `lq --upstream-bugs` matches
//      it, and default `lq` applies the other fixes and leaves the locale alone.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { GEN, firstDiff, lqBin, oracleRequire } from './lib.mjs';

const { checkAndAutofix } = oracleRequire('@shopify/theme-check-node');
const WORK = path.join(GEN, 'autofix');

const write = (root, files) => {
  fs.rmSync(root, { recursive: true, force: true });
  for (const [f, s] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true });
    fs.writeFileSync(path.join(root, f), s);
  }
};
const read = (root) => {
  const out = {};
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out[path.relative(root, p)] = fs.readFileSync(p, 'utf8');
    }
  };
  walk(root);
  return out;
};
const lq = (root, ...args) => spawnSync(lqBin(), ['check', '--path', root, '--auto-correct', '--output', 'json', ...args], { encoding: 'utf8', maxBuffer: 1 << 28 });

const LIQUID = {
  '.theme-check.yml': 'extends: theme-check:recommended\n',
  'layout/theme.liquid': '{{ content_for_header }}{{ content_for_layout }}',
  // A trailing `|` is one of LiquidHTMLSyntaxError's safe fixes.
  'snippets/a.liquid': '{{ product.title | upcase | }}\n',
  'snippets/b.liquid': "{{ 'é😀' | upcase | }}{% echo 'x' | }}{{ 'y' | upcase | }}\n",
  'locales/en.default.json': '{"a":"x","b":"y","c":{"d":"z"}}',
};

let failed = 0;
const report = (name, problem) => {
  console.log(`[autofix] ${name}: ${problem ? `FAIL ${problem}` : 'ok'}`);
  if (problem) failed++;
};
const changed = (before, after) => Object.keys(after).filter((f) => before[f] !== after[f]);

// 1. Everything applies.
const clean = { ...LIQUID, 'locales/fr.json': '{"a":"x"}' };
for (const [name, run] of [
  ['upstream', async (r) => checkAndAutofix(r)],
  ['bugs', async (r) => lq(r, '--upstream-bugs')],
  ['default', async (r) => lq(r)],
]) {
  write(path.join(WORK, `clean-${name}`), clean);
  await run(path.join(WORK, `clean-${name}`));
}
const up = read(path.join(WORK, 'clean-upstream'));
report('upstream actually fixes something', changed(clean, up).length >= 2 ? null : `changed ${changed(clean, up)}`);
for (const m of ['bugs', 'default']) {
  const d = firstDiff(up, read(path.join(WORK, `clean-${m}`)));
  report(`clean theme, lq ${m} equals upstream`, d && JSON.stringify(d).slice(0, 300));
}

// 2. AutofixAbort. Upstream walks files in glob order, and `locales/` sorts before `snippets/`.
const comment = '/*\n * generated by Shopify\n */\n{"a":"x"}\n';
const abort = { ...LIQUID, 'locales/fr.json': comment };
write(path.join(WORK, 'abort-upstream'), abort);
let rejected = null;
try {
  await checkAndAutofix(path.join(WORK, 'abort-upstream'));
} catch (e) {
  rejected = e.message;
}
const upA = read(path.join(WORK, 'abort-upstream'));
report('upstream rejects', rejected ? null : 'it resolved');
report('upstream fixes nothing', changed(abort, upA).length === 0 ? null : `changed ${changed(abort, upA)}`);

write(path.join(WORK, 'abort-bugs'), abort);
const bugsRun = lq(path.join(WORK, 'abort-bugs'), '--upstream-bugs');
const d = firstDiff(upA, read(path.join(WORK, 'abort-bugs')));
report('lq --upstream-bugs equals upstream', d && JSON.stringify(d).slice(0, 300));
report('lq --upstream-bugs exits nonzero', bugsRun.status !== 0 ? null : 'exit 0');

write(path.join(WORK, 'abort-default'), abort);
const defRun = lq(path.join(WORK, 'abort-default'));
const defA = read(path.join(WORK, 'abort-default'));
report('default lq keeps the comment-header locale', defA['locales/fr.json'] === comment ? null : 'rewritten');
report('default lq fixes the Liquid files', defA['snippets/a.liquid'] !== abort['snippets/a.liquid'] ? null : 'unchanged');
report('default lq warns', /skipped --auto-correct for .*fr\.json/.test(defRun.stderr) ? null : `stderr: ${defRun.stderr.slice(0, 200)}`);

console.log(`[autofix] ${failed} failed`);
process.exit(failed ? 1 : 0);
